const healthCheck = (req, res) => {
    return res.json({
        status:    'ok',
        module:    'AI Agent',
        version:   '1.0.0',
        model:     aiService.getModelName(),
        timestamp: new Date().toISOString(),
    });
};

module.exports = {
    handleChat,
    getHistory,
    clearHistory,
    healthCheck,
};
