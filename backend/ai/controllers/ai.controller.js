const aiService = require('../services/ai.service');
const aiHistory = require('../services/ai.history');
const { cleanInput } = require('../utils/ai.utils');

/**
 * AI Controller
 *
 * Handles HTTP request/response for the AI module.
 * All business logic and data access lives in the service and tool layers.
 */

// ---------------------------------------------------------------------------
// POST /api/ai/chat
// ---------------------------------------------------------------------------

/**
 * Handle an AI chat request.
 *
 * Expected request body:
 *   { message: string, sessionId: string }
 *
 * sessionId is a UUID generated by the frontend per conversation.
 * It is used to scope history retrieval and persistence.
 */
const handleChat = async (req, res) => {
    try {
        const { message, sessionId } = req.body;
        const sanitizedMessage = cleanInput(message);

        // sessionId is required — frontend must generate a UUID per conversation
        if (!sessionId || typeof sessionId !== 'string') {
            return res.status(400).json({
                success: false,
                error:   'sessionId is required. Generate a UUID on the frontend per conversation.',
            });
        }

        const result = await aiService.generateResponse(
            req.userId,     // from JWT — never from body
            req.userRole,   // from JWT — never from body
            sanitizedMessage,
            sessionId.trim()
        );

        return res.json({
            success:   true,
            response:  result.response,
            toolUsed:  result.toolUsed,
            model:     result.model,
            sessionId: sessionId.trim(),
            timestamp: result.timestamp,
        });

    } catch (error) {
        console.error('[AI Controller] handleChat error:', error.message);

        // Surface API-key misconfiguration clearly
        if (error.message.includes('GROQ_API_KEY') || error.message.includes('GEMINI_API_KEY')) {
            return res.status(503).json({
                success: false,
                error:   'AI service is not configured. Please contact the administrator.',
            });
        }

        // Surface safety filter blocks
        if (error.message.includes('safety') || error.message.includes('moderation')) {
            return res.status(422).json({
                success: false,
                error:   'Your message was blocked by the AI safety filter. Please rephrase.',
            });
        }

        // Surface Quota / Rate Limit errors (Groq 429)
        if (error.message.includes('429') || error.message.includes('rate_limit') || error.message.includes('Rate limit')) {
            return res.status(429).json({
                success: false,
                error:   'QUOTA_EXCEEDED',
                message: 'Groq API rate limit reached. Please wait a moment and try again.'
            });
        }

        return res.status(500).json({
            success: false,
            error:   'The AI service encountered an error. Please try again.',
        });
    }
};

// ---------------------------------------------------------------------------
// GET /api/ai/history
// ---------------------------------------------------------------------------

/**
 * Retrieve conversation history for the authenticated user's session.
 *
 * Query params: sessionId (required)
 */
const getHistory = async (req, res) => {
    try {
        const { sessionId } = req.query;

        if (!sessionId) {
            return res.status(400).json({
                success: false,
                error:   'sessionId query parameter is required.',
            });
        }

        const rows = await aiHistory.getHistoryForDisplay(req.userId, sessionId, 50);

        return res.json({
            success:   true,
            sessionId,
            count:     rows.length,
            history:   rows,
        });

    } catch (error) {
        console.error('[AI Controller] getHistory error:', error.message);
        return res.status(500).json({ success: false, error: 'Could not retrieve history.' });
    }
};

// ---------------------------------------------------------------------------
// DELETE /api/ai/history
// ---------------------------------------------------------------------------

/**
 * Clear conversation history for the authenticated user's session.
 *
 * Query params: sessionId (required)
 */
const clearHistory = async (req, res) => {
    try {
        const { sessionId } = req.query;

        if (!sessionId) {
            return res.status(400).json({
                success: false,
                error:   'sessionId query parameter is required.',
            });
        }

        const deleted = await aiHistory.clearHistory(req.userId, sessionId);

        return res.json({
            success:       true,
            sessionId,
            deletedTurns:  deleted,
            message:       `Cleared ${deleted} conversation turn(s).`,
        });

    } catch (error) {
        console.error('[AI Controller] clearHistory error:', error.message);
        return res.status(500).json({ success: false, error: 'Could not clear history.' });
    }
};

// ---------------------------------------------------------------------------
